"""Seed pipeline for the slang KB (Phase 5.1).

Ingests a CSV of slang entries (term, meaning, origin, region, first_seen,
example, adult_friendly_explanation), embeds each term, and either:

  * (default) loads them into the local KB and reports rows + embeddings, or
  * --emit-sql : prints INSERT statements with pgvector literals, so the same
    curated data can seed the production `slang_terms` table (migration 0002).

Run:  python -m scripts.seed_slang [path/to/terms.csv] [--emit-sql]

Any CSV with the same columns works (e.g. an Urban Dictionary / KnowYourMeme
export reduced to these fields with region + date tags).
"""

from __future__ import annotations

import csv
import sys
from pathlib import Path

from services.genz.base import EMBED_DIM, SlangTerm
from services.genz.embedder import get_text_embedder

DEFAULT_CSV = Path(__file__).parent.parent / "services" / "genz" / "seed" / "slang_seed.csv"


def _rows(path: Path) -> list[SlangTerm]:
    with path.open(newline="", encoding="utf-8") as fh:
        return [
            SlangTerm(**{k: (row.get(k) or "") for k in SlangTerm.__annotations__})
            for row in csv.DictReader(fh)
            if (row.get("term") or "").strip()
        ]


def _vector_literal(vec: list[float]) -> str:
    return "[" + ",".join(f"{x:.6f}" for x in vec) + "]"


def emit_sql(terms: list[SlangTerm]) -> None:
    embedder = get_text_embedder()
    print("-- Generated by scripts.seed_slang --emit-sql")
    for t in terms:
        vec = _vector_literal(embedder.embed(t.context_text()))

        def q(s: str) -> str:
            return "'" + s.replace("'", "''") + "'"

        cols = (
            "term, meaning, origin, region, first_seen, example, "
            "adult_friendly_explanation, embedding"
        )
        vals = (
            f"{q(t.term)}, {q(t.meaning)}, {q(t.origin)}, {q(t.region)}, "
            f"{q(t.first_seen)}, {q(t.example)}, {q(t.adult_friendly_explanation)}, {q(vec)}"
        )
        upsert = (
            "meaning=excluded.meaning, origin=excluded.origin, region=excluded.region, "
            "first_seen=excluded.first_seen, example=excluded.example, "
            "adult_friendly_explanation=excluded.adult_friendly_explanation, "
            "embedding=excluded.embedding"
        )
        print(
            f"insert into public.slang_terms ({cols}) values ({vals}) "
            f"on conflict (term) do update set {upsert};"
        )


def main() -> None:
    args = [a for a in sys.argv[1:] if a != "--emit-sql"]
    path = Path(args[0]) if args else DEFAULT_CSV
    terms = _rows(path)
    if "--emit-sql" in sys.argv[1:]:
        emit_sql(terms)
        return
    embedder = get_text_embedder()
    embedded = [(t, embedder.embed(t.context_text())) for t in terms]
    ok = all(len(vec) == EMBED_DIM and any(vec) for _, vec in embedded)
    print(f"CSV: {path}")
    print(f"Ingested {len(terms)} terms; every embedding is {EMBED_DIM}-dim non-zero: {ok}")
    for t, vec in embedded[:3]:
        print(f"  - {t.term:<12} region={t.region:<12} first_seen={t.first_seen} dim={len(vec)}")


if __name__ == "__main__":
    main()
